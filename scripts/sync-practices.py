#!/usr/bin/env python3
"""Copy the practice rows that apply to each folder from docs/PRACTICES.md into that
folder's README, between the PRACTICES markers. Run from the repo root after editing
docs/PRACTICES.md:  python3 scripts/sync-practices.py
"""
import re, pathlib

FOLDERS = {
    "api/README.md": ["API-", "DB-", "SEC-", "TST-", "OBS-1", "OBS-2", "DES-4", "CON-"],
    "web/README.md": ["SEC-1", "SEC-5", "SEC-7", "SEC-9", "API-2", "API-4", "CON-2", "CON-3", "CON-6"],
    "worker/README.md": ["API-5", "API-6", "API-7", "API-9", "DB-", "SEC-1", "SEC-2", "SEC-3", "CON-", "OBS-"],
    "k8s/README.md": ["INF-", "CON-", "SEC-1", "SEC-2", "SEC-5", "SEC-6", "SEC-8", "DB-2", "DB-3", "DB-12", "API-7", "API-8", "OBS-"],
    "scripts/README.md": ["INF-3", "INF-7", "DB-3", "DB-12", "TST-3", "TST-4", "SEC-1"],
    "tests/README.md": ["TST-", "DB-3", "API-7", "API-8"],
    ".github/workflows/README.md": ["TST-5", "INF-5", "SEC-1", "CON-3", "PRC-1"],
}
START, END = "<!-- PRACTICES:start -->", "<!-- PRACTICES:end -->"

rows = []
for line in pathlib.Path("docs/PRACTICES.md").read_text(encoding="utf-8").splitlines():
    m = re.match(r"\|\s*([A-Z]+-\d+)\s*\|(.*)\|(.*)\|(.*)\|\s*$", line)
    if m:
        rows.append((m.group(1), m.group(2).strip(), m.group(4).strip()))

for path, prefixes in FOLDERS.items():
    picked = [r for r in rows if any(r[0] == p or (p.endswith("-") and r[0].startswith(p)) for p in prefixes)]
    block = [START, "", "## Practices that apply here", "",
             "From [`docs/PRACTICES.md`](../docs/PRACTICES.md) (generated by `scripts/sync-practices.py`; edit the source, not this list). Paste this section into whatever tool you write code with.", "",
             "| ID | Practice | Here |", "|---|---|---|"]
    block += [f"| {i} | {t} | {w} |" for i, t, w in picked]
    block += ["", END]
    if path.startswith(".github"):
        block = [b.replace("](../docs/", "](../../docs/") for b in block]
    p = pathlib.Path(path); s = p.read_text(encoding="utf-8")
    if START in s:
        s = s[: s.index(START)] + "\n".join(block) + s[s.index(END) + len(END):]
    else:
        s = s.rstrip() + "\n\n" + "\n".join(block) + "\n"
    p.write_text(s, encoding="utf-8")
    print(f"{path}: {len(picked)} rows")
